//! `makefont`: converts FreeBSD's built-in console font,
//! `sys/dev/vt/font/vt_font_default.c` ("Terminus BSD Console", BSD-2-Clause),
//! to Rust, keeping its license notice.
//!
//! Usage: `makefont <vt_font_default.c> <output.rs>` (`make font`).

use std::fmt::Write as _;
use std::process::ExitCode;

/// The numbers inside the braces that follow `marker`.
fn numbers_after(src: &str, marker: &str) -> Result<Vec<u64>, String> {
    let at = src.find(marker).ok_or_else(|| format!("{marker} not found"))?;
    let rest = &src[at..];
    let open = rest.find('{').ok_or("no '{'")?;
    let close = rest.find("};").ok_or("no '};'")?;
    rest[open + 1..close]
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|t| !t.is_empty())
        .map(|t| {
            let (digits, radix) = match t.strip_prefix("0x") {
                Some(h) => (h, 16),
                None => (t, 10),
            };
            u64::from_str_radix(digits, radix).map_err(|_| format!("bad number {t}"))
        })
        .collect()
}

/// The `.vf_width` (or other) field of the font structure.
fn field(src: &str, name: &str) -> Result<u64, String> {
    let at = src.find(name).ok_or_else(|| format!("{name} not found"))?;
    let rest = &src[at + name.len()..];
    let eq = rest.find('=').ok_or("no '='")?;
    let end = rest.find(',').ok_or("no ','")?;
    rest[eq + 1..end].trim().parse().map_err(|_| format!("bad {name}"))
}

/// A map as little-endian `struct vfnt_map` records (src u32, dst u16, len u16).
fn map_bytes(triples: &[u64]) -> Result<Vec<u8>, String> {
    if !triples.len().is_multiple_of(3) {
        return Err("map is not made of triples".into());
    }
    let mut out = Vec::new();
    for t in triples.chunks(3) {
        out.extend_from_slice(&u32::try_from(t[0]).map_err(|_| "src")?.to_le_bytes());
        out.extend_from_slice(&u16::try_from(t[1]).map_err(|_| "dst")?.to_le_bytes());
        out.extend_from_slice(&u16::try_from(t[2]).map_err(|_| "len")?.to_le_bytes());
    }
    Ok(out)
}

fn bytes_rs(s: &mut String, name: &str, doc: &str, b: &[u8]) {
    let _ = writeln!(s, "/// {doc}");
    let _ = writeln!(s, "pub static {name}: [u8; {}] = [", b.len());
    for line in b.chunks(16) {
        s.push_str("   ");
        for x in line {
            let _ = write!(s, " {x:#04x},");
        }
        s.push('\n');
    }
    s.push_str("];\n\n");
}

fn generate(src: &str) -> Result<String, String> {
    // The license block is the first comment; keep it verbatim.
    let end = src.find("*/").ok_or("no license comment")? + 2;
    let license = &src[..end];
    let body = license.strip_prefix("/*-\n").ok_or("unexpected license header")?;
    let bytes: Vec<u8> = numbers_after(src, "font_bytes[")?
        .into_iter()
        .map(|v| u8::try_from(v).map_err(|_| "byte".to_string()))
        .collect::<Result<_, _>>()?;
    let normal = map_bytes(&numbers_after(src, "font_mapping_normal[")?)?;
    let bold = map_bytes(&numbers_after(src, "font_mapping_bold[")?)?;
    let (w, h) = (field(src, ".vf_width")?, field(src, ".vf_height")?);

    let mut s = String::new();
    s.push_str("/*-\n");
    s.push_str(body.trim_end_matches("*/").trim_end());
    s.push_str("\n *\n * DO NOT EDIT -- generated by tools/makefont from FreeBSD's\n");
    s.push_str(" * sys/dev/vt/font/vt_font_default.c (`make font`).\n */\n\n");
    s.push_str("//! The \"Terminus BSD Console\" 8x16 font, FreeBSD's built-in console\n");
    s.push_str("//! font (`vt_font_default`), in the layout of `sys::font`.\n\n");
    let _ = writeln!(s, "/// Glyph width in pixels.\npub const WIDTH: u32 = {w};");
    let _ = writeln!(s, "/// Glyph height in pixels.\npub const HEIGHT: u32 = {h};\n");
    bytes_rs(&mut s, "BITMAP", "The glyphs, one after the other.", &bytes);
    bytes_rs(&mut s, "MAP_NORMAL", "Code points to glyphs, normal weight.", &normal);
    bytes_rs(&mut s, "MAP_BOLD", "Code points to glyphs, bold.", &bold);
    Ok(s)
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().collect();
    let [_, input, output] = &args[..] else {
        eprintln!("usage: makefont <vt_font_default.c> <output.rs>");
        return ExitCode::from(2);
    };
    let result = std::fs::read_to_string(input)
        .map_err(|e| format!("{input}: {e}"))
        .and_then(|src| generate(&src))
        .and_then(|out| std::fs::write(output, out).map_err(|e| format!("{output}: {e}")));
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("makefont: {e}");
            ExitCode::FAILURE
        }
    }
}
